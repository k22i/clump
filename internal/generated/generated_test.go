func TestCompile(t *testing.T) {
	cases := []struct {
		pat string
		yes []string
		no  []string
	}{
		{"go.sum", []string{"go.sum", "tools/go.sum"}, []string{"go.sum.txt", "xgo.sum"}},
		{"*.min.js", []string{"a.min.js", "web/static/app.min.js"}, []string{"a.js", "min.js.map"}},
		{"vendor/", []string{"vendor/x/y.go", "php/vendor/a.php"}, []string{"vendor", "vendored/a.go"}},
		{"db/schema.rb", []string{"db/schema.rb"}, []string{"app/db/schema.rb"}},
		{"/db/schema.rb", []string{"db/schema.rb"}, []string{"app/db/schema.rb"}},
		{"**/db/schema.rb", []string{"db/schema.rb", "app/db/schema.rb"}, []string{"db/schema.rb.bak"}},
		{"**/drizzle/**/*.sql", []string{"drizzle/0001_init.sql", "apps/api/drizzle/0002_x.sql", "drizzle/sub/a.sql"}, []string{"drizzle/meta/_journal.json", "src/q.sql"}},
		{"**/meta/*_snapshot.json", []string{"drizzle/meta/0001_snapshot.json", "src/db/migrations/meta/0003_snapshot.json"}, []string{"meta/snapshot.json"}},
		{"__generated__/", []string{"src/__generated__/Query.graphql.ts"}, []string{"src/generated.ts"}},
		{"*.gen.*", []string{"src/routeTree.gen.ts"}, []string{"src/gen.ts", "src/generator.ts"}},
		{"src/api/client/", []string{"src/api/client/index.ts"}, []string{"src/api/clients.ts", "x/src/api/client/a.ts"}},
		{"a?c", []string{"abc"}, []string{"ac", "a/c"}},
	}
	for _, c := range cases {
		p, err := Compile(c.pat)
		if err != nil {
			t.Fatalf("%s: %v", c.pat, err)
		}
		for _, y := range c.yes {
			if !p.Match(y) {
				t.Errorf("%q should match %q", c.pat, y)
			}
		}
		for _, n := range c.no {
			if p.Match(n) {
				t.Errorf("%q should not match %q", c.pat, n)
			}
		}
	}
	for _, bad := range []string{"", "  ", "/", `a\b`} {
		if _, err := Compile(bad); err == nil {
			t.Errorf("Compile(%q): want an error", bad)
		}
	}
	if _, err := CompileAll(Builtin); err != nil {
		t.Fatalf("builtin: %v", err)
	}
}

func parse(t *testing.T, patch string) *gitdiff.Diff {
	t.Helper()
	d, err := gitdiff.Parse(patch)
	if err != nil {
		t.Fatal(err)
	}
	return d
}

// added is a one-hunk patch adding path with the given lines.
func added(path string, lines ...string) string {
	var b strings.Builder
	b.WriteString("diff --git a/" + path + " b/" + path + "\nnew file mode 100644\n--- /dev/null\n+++ b/" + path + "\n")
	b.WriteString("@@ -0,0 +1," + strconv.Itoa(len(lines)) + " @@\n")
	for _, l := range lines {
		b.WriteString("+" + l + "\n")
	}
	return b.String()
}

// modified is a one-hunk patch changing line start of path.
func modified(path string, start int, ctx string) string {
	s := strconv.Itoa(start)
	return "diff --git a/" + path + " b/" + path + "\n--- a/" + path + "\n+++ b/" + path + "\n" +
		"@@ -" + s + ",2 +" + s + ",2 @@\n " + ctx + "\n-old\n+new\n"
}

func reasons(d *gitdiff.Diff) map[string]string {
	out := map[string]string{}
	for _, f := range d.Files {
		out[f.Path()] = f.Generated
	}
	return out
}

func TestMark(t *testing.T) {
	patch := modified("go.sum", 10, "x") +
		modified("src/main.go", 20, "x") +
		added("internal/db/models.go", "// Code generated by sqlc. DO NOT EDIT.", "package db") +
		added("src/q.ts", "/* eslint-disable */", "// @generated by relay-compiler", "export {}") +
		added("migrations/0003_users.sql", "CREATE TABLE users (id int);", "--> statement-breakpoint", "CREATE INDEX x ON users (id);") +
		added("api/Client.cs", "// <auto-generated>", "class C {}") +
		added("src/strings.go", "package src", `const doc = "// Code generated DO NOT EDIT"`) +
		modified("src/late.go", 40, "// Code generated by x. DO NOT EDIT.") +
		modified("Cargo.lock", 1, "# This file is automatically @generated by Cargo.") +
		added("src/keep/go.sum", "x") +
		added("src/extra/out.txt", "x")

	det, err := New(Options{Detect: true, Builtin: true, Patterns: []string{"src/extra/"}, Review: []string{"src/keep/"}})
	if err != nil {
		t.Fatal(err)
	}
	d := parse(t, patch)
	det.Mark(context.Background(), d, "")
	want := map[string]string{
		"go.sum":                    "pattern go.sum",
		"src/main.go":               "",
		"internal/db/models.go":     "marker DO NOT EDIT",
		"src/q.ts":                  "marker @generated",
		"migrations/0003_users.sql": "marker statement-breakpoint (drizzle)",
		"api/Client.cs":             "marker auto-generated",
		"src/strings.go":            "", // a string literal, not a comment
		"src/late.go":               "", // the marker is not near the top
		"Cargo.lock":                "pattern Cargo.lock",
		"src/keep/go.sum":           "", // review wins over the built-in pattern
		"src/extra/out.txt":         "pattern src/extra/",
	}
	got := reasons(d)
	for p, w := range want {
		if got[p] != w {
			t.Errorf("%s: Generated = %q, want %q", p, got[p], w)
		}
	}
	if sig := Signature(d); sig != "0,2,3,4,5,8,10" {
		t.Errorf("Signature = %q", sig)
	}

	// builtin = false keeps only the user's patterns and the markers.
	det2, _ := New(Options{Detect: true, Patterns: []string{"src/extra/"}})
	det2.Mark(context.Background(), d, "")
	if g := reasons(d); g["go.sum"] != "" || g["src/extra/out.txt"] == "" || g["src/q.ts"] == "" {
		t.Errorf("builtin=false: %v", g)
	}
	// detect = false clears every mark.
	det3, _ := New(Options{Detect: false, Builtin: true})
	det3.Mark(context.Background(), d, "")
	if Signature(d) != "" {
		t.Errorf("detect=false: %v", reasons(d))
	}
	// A nil detector also clears.
	var nilDet *Detector
	d.Files[0].Generated = "x"
	nilDet.Mark(context.Background(), d, "")
	if d.Files[0].Generated != "" {
		t.Error("nil detector kept a mark")
	}
}

func TestMarkDrizzleSnapshots(t *testing.T) {
	snap := []string{"{", `  "version": "8",`, `  "dialect": "postgres",`, `  "id": "46e6",`, `  "prevIds": [`, `    "257b"`, "  ],"}
	patch := added("packages/db/src/migrations/20261124155802_light_pride/snapshot.json", snap...) +
		added("db/out/0001_snapshot_copy.json", `{`, `  "id": "a",`, `  "prevId": "b",`, `  "version": "7",`, `  "dialect": "postgresql"`) +
		added("src/config.json", `{`, `  "dialect": "postgres",`, `  "name": "x"`) +
		added("packages/db/src/migrations/20261124155802_light_pride/migration.sql", `CREATE TABLE "t" ("id" int);`)
	det, err := New(Options{Detect: true, Builtin: true})
	if err != nil {
		t.Fatal(err)
	}
	d := parse(t, patch)
	det.Mark(context.Background(), d, "")
	want := map[string]string{
		"packages/db/src/migrations/20261124155802_light_pride/snapshot.json": "pattern **/migrations/*/snapshot.json",
		"db/out/0001_snapshot_copy.json":                                      "marker snapshot (drizzle)",
		"src/config.json":                                                     "", // "dialect" alone is not a snapshot
		"packages/db/src/migrations/20261124155802_light_pride/migration.sql": "", // the SQL itself is reviewed
	}
	got := reasons(d)
	for p, w := range want {
		if got[p] != w {
			t.Errorf("%s: Generated = %q, want %q", p, got[p], w)
		}
	}
}

func TestParseCheckAttr(t *testing.T) {
	out := "a.go\x00linguist-generated\x00set\x00a.go\x00linguist-vendored\x00unspecified\x00" +
		"b.lock\x00linguist-generated\x00false\x00b.lock\x00linguist-vendored\x00unspecified\x00" +
		"lib/x.js\x00linguist-generated\x00unspecified\x00lib/x.js\x00linguist-vendored\x00true\x00" +
		"c.go\x00linguist-generated\x00unspecified\x00c.go\x00linguist-vendored\x00unspecified\x00"
	got := parseCheckAttr([]byte(out))
	want := map[string]attrState{"a.go": attrGenerated, "b.lock": attrReviewed, "lib/x.js": attrVendored}
	if len(got) != len(want) {
		t.Fatalf("got %v", got)
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s = %v, want %v", k, got[k], v)
		}
	}
}

func TestMarkGitattributes(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	repo := t.TempDir()
	if out, err := exec.Command("git", "-C", repo, "init", "-q").CombinedOutput(); err != nil {
		t.Fatalf("git init: %v %s", err, out)
	}
	attrs := "api/gen/** linguist-generated\npackage-lock.json -linguist-generated\nthird/** linguist-vendored\n"
	if err := os.WriteFile(filepath.Join(repo, ".gitattributes"), []byte(attrs), 0o644); err != nil {
		t.Fatal(err)
	}
	d := parse(t, modified("api/gen/client.ts", 10, "x")+modified("package-lock.json", 10, "x")+
		modified("third/lib.c", 10, "x")+modified("src/a.ts", 10, "x"))
	det, _ := New(Options{Detect: true, Builtin: true})
	det.Mark(context.Background(), d, repo)
	want := map[string]string{
		"api/gen/client.ts": "linguist-generated",
		"package-lock.json": "", // -linguist-generated overrides the built-in pattern
		"third/lib.c":       "linguist-vendored",
		"src/a.ts":          "",
	}
	got := reasons(d)
	for p, w := range want {
		if got[p] != w {
			t.Errorf("%s: Generated = %q, want %q", p, got[p], w)
		}
	}
}
