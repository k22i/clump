package generated

import (
	"bytes"
	"context"
	"os/exec"
	"path"
	"regexp"
	"strconv"
	"strings"

	"github.com/k22i/clump/internal/gitdiff"
)

type Options struct {
	Detect   bool
	Builtin  bool
	Patterns []string
	Review   []string
}

type Detector struct {
	on        bool
	review    []Pattern
	patterns  []Pattern
	builtin   []Pattern
	checkAttr func(ctx context.Context, repo string, paths []string) (map[string]attrState, error)
}

func New(o Options) (*Detector, error) {
	d := &Detector{on: o.Detect, checkAttr: gitCheckAttr}
	var err error
	if d.review, err = CompileAll(o.Review); err != nil {
		return nil, err
	}
	if d.patterns, err = CompileAll(o.Patterns); err != nil {
		return nil, err
	}
	if o.Builtin {
		if d.builtin, err = CompileAll(Builtin); err != nil {
			return nil, err
		}
	}
	return d, nil
}

const markerLines = 10

var (
	doNotEditRe   = regexp.MustCompile(`(?i)generated.*\b(do not|don't|dont) (edit|modify)\b|\b(do not|don't|dont) (edit|modify)\b.*generated`)
	markerRe      = regexp.MustCompile(`@generated\b|(?i)<auto-generated|\bauto-?generated\b|\bautomatically generated\b|\bgenerated automatically\b`)
	drizzleRe     = regexp.MustCompile(`^--> statement-breakpoint\s*$`)
	snapDialectRe = regexp.MustCompile(`^\s*"dialect"\s*:`)
	snapPrevRe    = regexp.MustCompile(`^\s*"prevIds?"\s*:`)
)

func (det *Detector) Mark(ctx context.Context, d *gitdiff.Diff, repo string) {
	if d == nil {
		return
	}
	for _, f := range d.Files {
		f.Generated = ""
	}
	if det == nil || !det.on || len(d.Files) == 0 {
		return
	}
	var attrs map[string]attrState
	if repo != "" && det.checkAttr != nil {
		paths := make([]string, 0, len(d.Files))
		for _, f := range d.Files {
			paths = append(paths, f.Path())
		}
		attrs, _ = det.checkAttr(ctx, repo, paths)
	}
	for _, f := range d.Files {
		f.Generated = det.reason(f, attrs[f.Path()])
	}
}

func (det *Detector) reason(f *gitdiff.File, attr attrState) string {
	p := f.Path()
	if _, ok := firstMatch(det.review, p); ok {
		return ""
	}
	switch attr {
	case attrGenerated:
		return "linguist-generated"
	case attrVendored:
		return "linguist-vendored"
	case attrReviewed:
		return ""
	}
	if m, ok := firstMatch(det.patterns, p); ok {
		return "pattern " + m.Text
	}
	if m, ok := firstMatch(det.builtin, p); ok {
		return "pattern " + m.Text
	}
	return markerReason(f)
}

func markerReason(f *gitdiff.File) string {
	ext := path.Ext(f.Path())
	sql := strings.EqualFold(ext, ".sql")
	json := strings.EqualFold(ext, ".json")
	var dialect, prev bool
	for _, h := range f.Hunks {
		if h.Pseudo {
			continue
		}
		oldNo, newNo := h.OldStart, h.NewStart
		for _, raw := range h.Lines {
			prefix, text := " ", ""
			if raw != "" {
				prefix, text = raw[:1], raw[1:]
			}
			top := false
			switch prefix {
			case "-":
				top = oldNo <= markerLines
				oldNo++
			case "+":
				top = newNo <= markerLines
				newNo++
			case "\\":
				continue
			default:
				top = oldNo <= markerLines || newNo <= markerLines
				oldNo++
				newNo++
			}
			if sql && drizzleRe.MatchString(text) {
				return "marker statement-breakpoint (drizzle)"
			}
			if json && top {
				dialect = dialect || snapDialectRe.MatchString(text)
				prev = prev || snapPrevRe.MatchString(text)
				if dialect && prev {
					return "marker snapshot (drizzle)"
				}
			}
			if !top || !isComment(text) {
				continue
			}
			if doNotEditRe.MatchString(text) {
				return "marker DO NOT EDIT"
			}
			if m := markerRe.FindString(text); m != "" {
				return "marker " + strings.TrimPrefix(m, "<")
			}
		}
	}
	return ""
}

var commentStarts = []string{"//", "#", "/*", "*", "--", "<!--", ";", "%", `"""`, "'''", "{-", "(*"}

func isComment(text string) bool {
	t := strings.TrimLeft(text, " \t")
	for _, c := range commentStarts {
		if strings.HasPrefix(t, c) {
			return true
		}
	}
	return false
}

type attrState int

const (
	attrNone attrState = iota
	attrGenerated
	attrVendored
	attrReviewed
)

func gitCheckAttr(ctx context.Context, repo string, paths []string) (map[string]attrState, error) {
	var in bytes.Buffer
	for _, p := range paths {
		in.WriteString(p)
		in.WriteByte(0)
	}
	cmd := exec.CommandContext(ctx, "git", "-C", repo, "check-attr", "-z", "--stdin", "linguist-generated", "linguist-vendored")
	cmd.Stdin = &in
	out, err := cmd.Output()
	if err != nil {
		return nil, err
	}
	return parseCheckAttr(out), nil
}

func parseCheckAttr(out []byte) map[string]attrState {
	parts := strings.Split(string(out), "\x00")
	res := map[string]attrState{}
	for i := 0; i+2 < len(parts); i += 3 {
		p, attr, val := parts[i], parts[i+1], parts[i+2]
		var st attrState
		switch val {
		case "set", "true":
			st = attrGenerated
			if attr == "linguist-vendored" {
				st = attrVendored
			}
		case "unset", "false":
			st = attrReviewed
		default:
			continue
		}
		cur := res[p]
		if cur == attrNone || cur == attrReviewed {
			res[p] = st
		}
	}
	return res
}

func Signature(d *gitdiff.Diff) string {
	var b strings.Builder
	for i, f := range d.Files {
		if f.Generated == "" {
			continue
		}
		if b.Len() > 0 {
			b.WriteByte(',')
		}
		b.WriteString(strconv.Itoa(i))
	}
	return b.String()
}
